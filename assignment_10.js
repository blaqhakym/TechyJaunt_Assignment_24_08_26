// Anonymous function

const sumBunniesAnoFn = function (whiteBunnies, blackBunnies) {
  return whiteBunnies + blackBunnies
};


console.log(sumBunniesAnoFn(10,20))


// Arrow function

const sumBunniesArrowFn = (whiteBunnies, blackBunnies)=> whiteBunnies+blackBunnies

console.log(sumBunniesArrowFn(10,20))